def test_digests_of_file_matches_independent_computation(tmp_path):
    payload = b"PK\x03\x04" + bytes(range(256)) * 7 + b"\n \t\r\n"
    path = tmp_path / "blob.bin"
    path.write_bytes(payload)

    with open(path, "rb") as handle:
        sha1, sha512, fingerprint, size = digests_of_file(handle)

    assert sha1 == hashlib.sha1(payload).hexdigest()
    assert sha512 == hashlib.sha512(payload).hexdigest()
    assert fingerprint == curseforge_fingerprint(payload)
    assert size == len(payload)


def test_digests_of_file_streams_consistently(tmp_path, monkeypatch):
    """The single-pass reader must give the same answer as hashing the whole buffer, even
    when the read size does not divide the file length."""
    payload = bytes((index * 13 + 7) % 256 for index in range(5000))
    path = tmp_path / "blob.bin"
    path.write_bytes(payload)

    import mod_update_checker.fingerprint as module

    monkeypatch.setattr(module, "_READ_CHUNK", 7)
    with open(path, "rb") as handle:
        sha1, sha512, fingerprint, size = module.digests_of_file(handle)

    assert sha1 == hashlib.sha1(payload).hexdigest()
    assert sha512 == hashlib.sha512(payload).hexdigest()
    assert fingerprint == curseforge_fingerprint(payload)
    assert size == len(payload)


def test_digests_of_empty_file(tmp_path):
    path = tmp_path / "empty.bin"
    path.write_bytes(b"")
    with open(path, "rb") as handle:
        sha1, sha512, fingerprint, size = digests_of_file(handle)
    assert sha1 == hashlib.sha1(b"").hexdigest()
    assert fingerprint == 0
    assert size == 0
